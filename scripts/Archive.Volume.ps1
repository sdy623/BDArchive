# Filesystem descriptors and human archive metadata have different namespaces.
# UDF-only authoring stays fixed; ISO/Joliet inputs remain documented metadata.
function Volume-Templates($C,$P) {
    $result=[ordered]@{udf=(Volume-LabelTemplate $C $P);iso9660='';joliet='';system='';volume_set='';publisher='';data_preparer='';application=''}
    foreach ($source in @((Optional-Field (Optional-Field $C 'numbering') 'volume_templates'),(Optional-Field $P 'VolumeTemplates'))) {
        if (!$source) { continue }
        $keys=if ($source -is [Collections.IDictionary]) { @($source.Keys) } else { @($source.PSObject.Properties.Name) }
        foreach ($key in $keys) {
            if ($key -eq 'udf' -or !$result.Contains($key)) { throw "Unknown volume template field: $key. UDF uses -VolumeLabelTemplate." }
            $result[$key]=[string]$source.$key
        }
    }
    [pscustomobject]$result
}
function Expand-ArchiveTemplate([string]$Template,$D) {
    $id=Disc-Identity $D
    $sha=[Security.Cryptography.SHA256]::Create()
    try { $token=([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes("$($id.catalog_id)/$($id.archive_set_id)")))).Replace('-','').Substring(0,16) } finally { $sha.Dispose() }
    $values=@{disc_id=$id.disc_id;prefix=$id.disc_prefix;number=('{0:D4}' -f $id.disc_number);disc_index=('{0:D6}' -f [int64]$id.disc_index);set_id=$id.archive_set_id;catalog_id=$id.catalog_id;volume_id=$id.volume_id;volume_index=('{0:D4}' -f $id.volume_index);volume_count=('{0:D4}' -f $id.volume_count);set_token=$token}
    $result=$Template
    foreach ($key in $values.Keys) { $result=$result.Replace('{'+$key+'}',[string]$values[$key]) }
    if ($result -match '[{}\x00-\x1F\x7F]') { throw 'Unknown template token or control character in volume metadata.' }
    $result
}
function New-VolumeMetadata($Templates,$D) {
    $values=[ordered]@{};$targets=[ordered]@{}
    foreach ($key in @('udf','iso9660','joliet','system','volume_set','publisher','data_preparer','application')) {
        $value=if ($key -eq 'udf') { Format-VolumeLabel $Templates.udf $D } else { Expand-ArchiveTemplate ([string]$Templates.$key) $D }
        if ($key -eq 'application' -and $value -and ($value.Length -gt 23 -or $value -cmatch '[^\x20-\x7E]')) { throw 'UDF Application must be at most 23 ASCII bytes. It will not be truncated.' }
        if ($key -eq 'application' -and $value -cne $value.Trim()) { throw 'Application cannot start or end with whitespace; the authoring backend may trim it.' }
        if ($key -notin @('udf','application') -and $value.Length -gt 128) { throw "Metadata field $key exceeds the toolkit limit of 128 characters." }
        $values[$key]=$value
        $targets[$key]=switch ($key) {
            'udf' {'UDF_LABEL_IMAPI2_OR_IMGBURN'}
            'volume_set' {'MANIFEST_ONLY_UDF_VOLUME_SET_GENERATED_BY_BACKEND'}
            'application' {'UDF_DESCRIPTOR_IMGBURN_ONLY'}
            default {'MANIFEST_ONLY_IN_UDF_MODE'}
        }
    }
    [pscustomobject]@{schema_version=1;filesystem='UDF';udf_revision='2.50';values=[pscustomobject]$values;targets=[pscustomobject]$targets;note='All fields are in DISC.json. Only UDF label is supported by IMAPI2; explicit Application requires ImgBurn. In ImgBurn 2.5.8.0 UDF Volume Set is generated by the backend, not taken from the Labels tab field. The requested volume_set and ISO9660/Joliet/System/Publisher/Data Preparer remain metadata only.'}
}
function Disc-VolumeMetadata($D) {
    $saved=Optional-Field $D 'authoring_metadata'
    if ($saved) { return $saved }
    $t=[pscustomobject]@{udf=(Disc-Identity $D).volume_label;iso9660='';joliet='';system='';volume_set='';publisher='';data_preparer='';application=''}
    New-VolumeMetadata $t $D
}
function Assert-VolumeBackend($D,[string]$Backend) {
    $m=Disc-VolumeMetadata $D
    if ($Backend -eq 'IMAPI2' -and $m.values.application) { throw 'This sealed plan specifies Application. Select the ImgBurn backend; IMAPI2 cannot write that requested descriptor.' }
}
function Write-ImgBurnProject($D,[string]$Source,[string]$Output,[ValidateSet('IMAGEFILE','DEVICE')][string]$OutputMode='IMAGEFILE') {
    # Documented ImgBurn .IBB project fields; live image-only test checks the
    # resulting UDF descriptors. No guessed CLI switches or registry changes.
    $m=Disc-VolumeMetadata $D;$sourcePath=Full-Path $Source
    if ($sourcePath -match '[\r\n]' -or (Test-Path -LiteralPath $Output)) { throw 'Unsafe project source or existing project output.' }
    $modeNumber=if ($OutputMode -eq 'DEVICE') {1} else {2}
    $lines=@('IBB','[START_BACKUP_OPTIONS]','BuildInputMode=1',('BuildOutputMode='+$modeNumber),'FileSystem=4','UDFRevision=4',
        'PreserveFullPathnames=0','RecurseSubdirectories=1','IncludeHiddenFiles=1','IncludeSystemFiles=1','IncludeArchiveFilesOnly=0','ClearArchiveAttribute=0',
        ('VolumeLabel_ISO9660='+$m.values.iso9660),('VolumeLabel_Joliet='+$m.values.joliet),('VolumeLabel_UDF='+$m.values.udf),
        ('Identifier_System='+$m.values.system),('Identifier_VolumeSet='+$m.values.volume_set),('Identifier_Publisher='+$m.values.publisher),
        ('Identifier_Preparer='+$m.values.data_preparer),('Identifier_Application='+$m.values.application),
        'Restrictions_UDF_DisableUnicodeSupport=0','BootableDisc_MakeImageBootable=0','[END_BACKUP_OPTIONS]','[START_BACKUP_LIST]',$sourcePath,'[END_BACKUP_LIST]')
    if (Test-Path -LiteralPath (Join-Path $sourcePath 'ARCHIVE-REFERENCES.json')) {
        # ImgBurn skips reparse files in folder mode. Advanced projects name
        # every physical source explicitly while preserving the optical tree.
        $cut=[Array]::IndexOf($lines,'[START_BACKUP_LIST]')
        $lines=@($lines[0..($cut-1)] | ForEach-Object {if($_ -ceq 'BuildInputMode=1'){'BuildInputMode=2'}else{$_}})
        $lines+='[START_BACKUP_LIST]'
        foreach($dir in @(Get-ChildItem -LiteralPath $sourcePath -Directory -Recurse -Force | Sort-Object FullName)) {
            Assert-NoLinks $dir.FullName
            $rel=Relative-Path $sourcePath $dir.FullName
            $parent=if($rel.Contains('/')){'\'+$rel.Substring(0,$rel.LastIndexOf('/')).Replace('/','\')+'\'}else{'\'}
            if($dir.Name -match '[|\r\n]'){throw 'Invalid project folder name'}
            $lines+=('D|'+$dir.Name+'|'+$parent+'|'+$dir.FullName+'\')
        }
        foreach($file in @(Tree-Files $sourcePath | Sort-Object FullName)) {
            $rel=Relative-Path $sourcePath $file.FullName
            $parent=if($rel.Contains('/')){'\'+$rel.Substring(0,$rel.LastIndexOf('/')).Replace('/','\')+'\'}else{'\'}
            $physical=Resolve-ArchiveFileReference $file.FullName
            if($file.Name -match '[|\r\n]' -or $physical -match '[|\r\n]'){throw 'Invalid project file path'}
            $lines+=('F|'+$file.Name+'|'+$parent+'|'+$physical)
        }
        $lines+='[END_BACKUP_LIST]'
    }
    [IO.Directory]::CreateDirectory((Split-Path (Full-Path $Output))) | Out-Null
    [IO.File]::WriteAllText((Full-Path $Output),(($lines -join "`r`n")+"`r`n"),[Text.Encoding]::Unicode)
    $Output
}
